num1= 10
num2= 20

#arithemetic operators
print("num1+num2",num1+num2)
print("num1-num2",num1-num2)
print("num1*num2",num1*num2)
print("num1/num2",num1/num2)
print("num1//num2",num1//num2)#double float
print("num1**num2",num1**num2)#exponential
print("num1%num2",num1%num2)#remainder after divide

#assignment operators
a =5
a += 2# same for -,*,/,//,**,%
print(a)

#comparison operators
x =3
y =4
print(x>y)
print(y>x)
print(x!=y)
